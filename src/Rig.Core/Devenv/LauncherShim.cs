namespace Rig.Core.Devenv;

/// <summary>
/// The <c>agent</c> launcher: a shim at the code root (<c>agent.sh</c>, and <c>agent.ps1</c> on Windows) running
/// <c>rig agent</c> from this checkout's C# CLI, and a marked block in the shell profile defining an <c>agent</c>
/// function that calls it without changing folder. Ported from devenv's <c>agent_launcher_setup</c> and
/// <c>agent_shortcut</c>.
/// </summary>
public static class LauncherShim
{
    /// <summary>The first line of the profile block.</summary>
    public const string Begin = "# >>> shared-utilities agent shortcut >>>";

    /// <summary>The last line of the profile block.</summary>
    public const string End = "# <<< shared-utilities agent shortcut <<<";

    /// <summary>The comment heading each shim.</summary>
    public const string Header =
        "# Generated by `devenv setup`. Do not edit by hand.\n"
        + "# Launches your preferred AI coding agent or selected flag (-agy, -ccc, -agywsl, -dng).";

    private const string BlockComment =
        "# Managed by `devenv` setup — do not edit between these markers.\n"
        + "# `agent` launches your preferred AI coding agent or selected flag (-agy, -ccc, -agywsl).";

    /// <summary>
    /// The main checkout behind <paramref name="checkout"/>: when it is a linked git worktree (its <c>.git</c> is a
    /// <c>gitdir:</c> file pointing into <c>.git/worktrees/</c>), the folder holding that <c>.git</c>; otherwise
    /// <paramref name="checkout"/>. The shim outlives any worktree, so it must never run one.
    /// </summary>
    public static string MainCheckout(string checkout)
    {
        var marker = Path.Join(checkout, ".git");
        if (!File.Exists(marker))
        {
            return checkout;
        }

        try
        {
            var line = File.ReadLines(marker).FirstOrDefault() ?? string.Empty;
            if (!line.StartsWith("gitdir:", StringComparison.Ordinal))
            {
                return checkout;
            }

            var gitDir = Path.GetFullPath(line["gitdir:".Length..].Trim(), checkout);
            var worktrees = Path.GetDirectoryName(Path.TrimEndingDirectorySeparator(gitDir));
            return worktrees is not null && Path.GetFileName(worktrees) == "worktrees" && Path.GetDirectoryName(worktrees) is { } common
                ? Path.GetDirectoryName(common) ?? checkout
                : checkout;
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            return checkout;
        }
    }

    /// <summary>The C# CLI project in <paramref name="checkout"/>, which the shims run.</summary>
    public static string CliProject(string checkout) => Path.Join(checkout, "src", "Rig.Cli");

    /// <summary>The body of <c>agent.ps1</c>.</summary>
    public static string PowerShell(string cliProject)
    {
        ArgumentNullException.ThrowIfNull(cliProject);
        return $"{Header}\ndotnet run --project \"{PowerShellDouble(cliProject)}\" -- agent @args\nexit $LASTEXITCODE\n";
    }

    /// <summary>The body of <c>agent.sh</c>; the project path uses forward slashes.</summary>
    public static string Posix(string cliProject) =>
        $"#!/usr/bin/env bash\n{Header}\nexec dotnet run --project \"{PosixDouble(Slashes(cliProject))}\" -- agent \"$@\"\n";

    /// <summary>The PowerShell profile block calling <paramref name="shim"/> with <c>@args</c>.</summary>
    public static string PowerShellBlock(string shim)
    {
        ArgumentNullException.ThrowIfNull(shim);
        return $"{Begin}\n{BlockComment}\nfunction agent {{\n    & '{shim.Replace("'", "''", StringComparison.Ordinal)}' @args\n}}\n{End}";
    }

    /// <summary>The POSIX profile block calling <paramref name="shim"/> with <c>"$@"</c>.</summary>
    public static string PosixBlock(string shim) =>
        $"{Begin}\n{BlockComment}\nagent() {{\n    \"{PosixDouble(Slashes(shim))}\" \"$@\"\n}}\n{End}";

    // A path as literal text inside double quotes: POSIX shells read \ " $ and ` there, PowerShell reads ` " and $.
    private static string PosixDouble(string text) =>
        text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("$", "\\$", StringComparison.Ordinal).Replace("`", "\\`", StringComparison.Ordinal);

    private static string PowerShellDouble(string text) =>
        text.Replace("`", "``", StringComparison.Ordinal).Replace("\"", "`\"", StringComparison.Ordinal).Replace("$", "`$", StringComparison.Ordinal);

    /// <summary>
    /// <paramref name="existing"/> with <paramref name="block"/> in place of the marked region, or appended after a
    /// blank line when there is none. The result ends with exactly one newline.
    /// </summary>
    public static string Upsert(string existing, string block)
    {
        ArgumentNullException.ThrowIfNull(existing);
        var begin = existing.IndexOf(Begin, StringComparison.Ordinal);
        var end = existing.IndexOf(End, StringComparison.Ordinal);
        if (begin != -1 && end > begin)
        {
            var before = existing[..begin].TrimEnd('\n');
            var after = existing[(end + End.Length)..].TrimStart('\n');
            return string.Join("\n\n", new[] { before, block, after }.Where(p => p.Length > 0)).TrimEnd('\n') + "\n";
        }

        var head = existing.TrimEnd('\n');
        return head.Length > 0 ? $"{head}\n\n{block}\n" : $"{block}\n";
    }

    /// <summary>
    /// The POSIX shell profile under <paramref name="home"/>: <c>.zshrc</c> when <paramref name="shell"/> is zsh or a
    /// <c>.zshrc</c> exists, else <c>.bashrc</c>.
    /// </summary>
    public static string PosixProfile(string home, string? shell) =>
        Path.Join(home, (shell ?? string.Empty).Contains("zsh", StringComparison.Ordinal) || File.Exists(Path.Join(home, ".zshrc")) ? ".zshrc" : ".bashrc");

    /// <summary>
    /// The active PowerShell profile under <paramref name="home"/>, honouring OneDrive redirection: a redirected
    /// <c>Documents/PowerShell</c> profile, then the standard one, then the same two for Windows PowerShell, else the
    /// standard PowerShell path.
    /// </summary>
    public static string PowerShellProfile(string home)
    {
        const string file = "Microsoft.PowerShell_profile.ps1";
        var standard = Path.Join(home, "Documents", "PowerShell", file);
        return Redirected(home, "PowerShell", file)
            ?? (File.Exists(standard) ? standard : null)
            ?? Redirected(home, "WindowsPowerShell", file)
            ?? Existing(Path.Join(home, "Documents", "WindowsPowerShell", file))
            ?? standard;
    }

    private static string? Redirected(string home, string folder, string file) =>
        !Directory.Exists(home)
            ? null
            : Directory.EnumerateDirectories(home)
                .Order(StringComparer.Ordinal)
                .Select(dir => Path.Join(dir, "Documents", folder, file))
                .FirstOrDefault(File.Exists);

    private static string? Existing(string path) => File.Exists(path) ? path : null;

    private static string Slashes(string path)
    {
        ArgumentNullException.ThrowIfNull(path);
        return path.Replace('\\', '/');
    }
}
