def check_root_size(text: str, rules: AgentsMdRules) -> list[Finding]:
    """Fail a root file over its line budget."""
    lines = text.count("\n") + 1
    if lines <= rules.max_lines:
        return []
    return [
        Finding(
            check="root-size",
            severity=Severity.ERROR,
            path=AGENTS_FILENAME,
            message=(
                f"{lines} lines against a budget of {rules.max_lines}. "
                f"Move domain rules into `docs/` and point at them."
            ),
        )
    ]


def check_duplicate_headings(text: str) -> list[Finding]:
    """Fail a root file that says the same thing twice under one heading."""
    seen: dict[str, int] = {}
    out: list[Finding] = []
    for number, line in enumerate(text.splitlines(), start=1):
        match = _HEADING.match(line)
        if not match:
            continue
        title = match.group(2).strip()
        if title in seen:
            out.append(
                Finding(
                    check="duplicate-heading",
                    severity=Severity.ERROR,
                    path=AGENTS_FILENAME,
                    line=number,
                    message=f"`{title}` already appears at line {seen[title]}. Two copies contradict each other.",
                )
            )
        else:
            seen[title] = number
    return out


def strip_code(text: str) -> str:
    """Blank out fenced blocks and inline code spans.

    A link inside a code span is an *example* of link syntax, not a pointer —
    documenting `--attach` by showing `![alt](./shot.png)` must not be read as a
    promise that `./shot.png` exists.
    """
    kept: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if _FENCE.match(line):
            in_fence = not in_fence
            kept.append("")
            continue
        kept.append("" if in_fence else _CODE_SPAN.sub("", line))
    return "\n".join(kept)


def _relative_targets(text: str) -> Iterable[str]:
    """Yield link targets that point at a path in this repo."""
    for match in _MD_LINK.finditer(strip_code(text)):
        target = match.group(1).split("#", 1)[0].strip()
        if not target or target.startswith(("http://", "https://", "mailto:", "#")):
            continue
        # Markdown links percent-encode spaces (`Repo%20Docs%20Index.md`); the file on disk does not.
        yield unquote(target)


def _resolve(base: pathlib.Path, target: str) -> pathlib.Path | None:
    """Resolve a link target under `base`; None when it cannot name a file (a decoded `%00`)."""
    try:
        return (base / target).resolve()
    except (ValueError, OSError):
        return None


def check_pointers(repo_path: pathlib.Path, docs: Sequence[pathlib.Path]) -> list[Finding]:
    """Fail any relative link that does not resolve.

    Progressive disclosure is only safe if the pointers hold — a root file that
    delegates to a doc that moved is worse than one that inlined the content.
    """
    out: list[Finding] = []
    for doc in docs:
        try:
            text = doc.read_text(encoding="utf-8")
        except OSError:
            continue
        rel = doc.relative_to(repo_path).as_posix()
        for target in _relative_targets(text):
            resolved = _resolve(doc.parent, target)
            if resolved is None or not resolved.exists():
                out.append(
                    Finding(
                        check="pointer-integrity",
                        severity=Severity.ERROR,
                        path=rel,
                        message=f"Link target `{target}` does not exist.",
                    )
                )
    return out


def check_docs_orphans(repo_path: pathlib.Path, docs: Sequence[pathlib.Path]) -> list[Finding]:
    """Report docs nothing links to.

    An unreachable doc is not progressive disclosure, it is a file an agent will
    never load. A directory carrying its own `README.md` is treated as
    self-indexing and exempt.
    """
    linked: set[pathlib.Path] = set()
    for doc in docs:
        try:
            text = doc.read_text(encoding="utf-8")
        except OSError:
            continue
        for target in _relative_targets(text):
            resolved = _resolve(doc.parent, target)
            if resolved is not None and resolved.exists():
                linked.add(resolved)

    out: list[Finding] = []
    for doc in docs:
        if doc.name == AGENTS_FILENAME or doc.resolve() in linked:
            continue
        # A folder index that fails to link this doc is reported by `folder-index` instead.
        if _is_index(doc) or _folder_index(doc.parent) is not None:
            continue
        out.append(
            Finding(
                check="docs-orphan",
                severity=Severity.WARN,
                path=doc.relative_to(repo_path).as_posix(),
                message="Nothing links here, so no agent will load it. Point at it or delete it.",
            )
        )
    return out


_GIT_SYMLINK_MODE = "120000"


def _is_symlink_or_placeholder(path: pathlib.Path) -> bool:
    """A symlink, or the plain file git writes in place of a committed symlink.

    Without symlink support (Windows with ``core.symlinks=false``) git checks a
    symlink out as a regular file holding just the target path. The index still
    records it with the symlink mode, so it is the same committed link, not a copy
    that can drift. A regular file that merely contains ``AGENTS.md`` is not.
    """
    if path.is_symlink():
        return True
    return _git_index_mode(path) == _GIT_SYMLINK_MODE and _names_agents_md(path)


def _names_agents_md(path: pathlib.Path) -> bool:
    """Whether the checked-out placeholder still holds just the link target."""
    try:
        return path.read_text(encoding="utf-8").strip() == "AGENTS.md"
    except (OSError, UnicodeDecodeError):
        return False


def _git_index_mode(path: pathlib.Path) -> str | None:
    """The file mode git's index records for *path*, or None if untracked or not a repo."""
    listed = proc.git("ls-files", "--stage", "--", path.name, cwd=path.parent, timeout=10)
    fields = listed.out.split(maxsplit=1)
    return fields[0] if listed.ok and fields else None


def check_claude_md(repo_path: pathlib.Path, rules: AgentsMdRules) -> list[Finding]:
    """Enforce the shape of `CLAUDE.md` — a symlink, or absent."""
    if rules.claude_md == "any":
        return []
    path = repo_path / "CLAUDE.md"
    exists = path.is_symlink() or path.exists()
    if rules.claude_md == "absent" and exists:
        return [
            Finding(
                check="claude-md-shape",
                severity=Severity.WARN,
                path="CLAUDE.md",
                message="Policy is `absent`, but this file exists. Agents read AGENTS.md directly.",
            )
        ]
    if rules.claude_md == "symlink" and exists and not _is_symlink_or_placeholder(path):
        return [
            Finding(
                check="claude-md-shape",
                severity=Severity.WARN,
                path="CLAUDE.md",
                message="A copy, not a symlink — so it drifts from AGENTS.md. Run `ln -sf AGENTS.md CLAUDE.md`.",
            )
        ]
    return []


def check_bespoke_agent_files(repo_path: pathlib.Path, rules: AgentsMdRules) -> list[Finding]:
    """Fail a repository that still carries a per-tool instruction file.

    `AGENTS.md` is the single source of truth, and the tools that own these names
    read their own file *instead* of it. A copy therefore drifts silently, and a
    pointer only adds indirection the tool does not need — the same reasoning that
    removed `CLAUDE.md`. A tool *feature* definition is not in the list; see
    `agent_files.py` for which shapes were deliberately excluded.
    """
    out: list[Finding] = []
    for relative in rules.bespoke_agent_files:
        path = repo_path / relative.rstrip("/")
        if not (path.is_symlink() or path.exists()):
            continue
        out.append(
            Finding(
                check="bespoke-agent-file",
                severity=Severity.ERROR,
                path=relative.rstrip("/"),
                message="Merge anything worth keeping into AGENTS.md, then delete this. "
                "The tool that owns this name reads it instead of AGENTS.md.",
            )
        )
    return out


def _looks_like_path(candidate: str) -> bool:
    """Return True for backticked text that is plausibly a repo path.

    Requires a directory separator on purpose. Without it, suffix patterns like
    `.test.ts` and bare filenames read as paths, which is how a naive version of
    this check produced ten false positives out of fourteen.
    """
    # `~/...` lives in a home directory, not the repo, so it can never be checked from here.
    if "/" not in candidate or candidate.startswith(("/", "~", "http", "@", "-")):
        return False
    if any(ch in candidate for ch in " *<>|$(){}"):
        return False
    return "." in candidate.rsplit("/", 1)[-1]


def check_path_liveness(repo_path: pathlib.Path, text: str) -> list[Finding]:
    """Report path-shaped strings that no longer exist.

    Stale paths are the fastest-rotting content in an agent file, and they
    actively mislead rather than merely going quiet.
    """
    out: list[Finding] = []
    for number, line in enumerate(text.splitlines(), start=1):
        for match in _BACKTICKED.finditer(line):
            candidate = match.group(1).strip()
            if _looks_like_path(candidate) and not (repo_path / candidate).exists():
                out.append(
                    Finding(
                        check="path-liveness",
                        severity=Severity.WARN,
                        path=AGENTS_FILENAME,
                        line=number,
                        message=f"`{candidate}` does not exist. Describe the capability, not the location.",
                    )
                )
    return out


def check_required_content(text: str, rules: AgentsMdRules) -> list[Finding]:
    """Fail a root file missing one of the three things it must answer."""
    lowered = text.lower()
    head = "\n".join(text.splitlines()[:12])
    present = {
        "description": any(
            line.strip() and not line.startswith(("#", "-", "|", "`", ">")) for line in head.splitlines()
        ),
        "package_manager": any(manager in lowered for manager in _PACKAGE_MANAGERS),
        "commands": "## commands" in lowered or "```" in text,
    }
    return [
        Finding(
            check="required-content",
            severity=Severity.ERROR,
            path=AGENTS_FILENAME,
            message=f"No {name.replace('_', ' ')} found. An agent cannot orient without it.",
        )
        for name in rules.require
        if not present.get(name, True)
    ]


def check_generation_markers(text: str) -> list[Finding]:
    """Fail an auto-generated root file — they favour completeness over restraint."""
    lowered = text.lower()
    marker = next((m for m in _GENERATION_MARKERS if m in lowered), None)
    if marker is None:
        return []
    return [
        Finding(
            check="generation-marker",
            severity=Severity.ERROR,
            path=AGENTS_FILENAME,
            message=f"Looks auto-generated (`{marker}`). Write it by hand; generators do not exercise restraint.",
        )
    ]


def collect_metrics(text: str) -> dict[str, int]:
    """Return the report-only numbers. Thresholds are a judgement, so no finding."""
    lines = text.splitlines()
    sections: list[int] = []
    current = 0
    for line in lines:
        if _HEADING.match(line):
            sections.append(current)
            current = 0
        else:
            current += 1
    sections.append(current)
    return {
        "instruction-count": sum(1 for line in lines if _INSTRUCTION.match(line)),
        "forcing-language": len(_FORCING.findall(text)),
        "section-outlier": max(sections) if sections else 0,
    }


