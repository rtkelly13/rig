def _markdown_files(repo_path: pathlib.Path) -> list[pathlib.Path]:
    """Return AGENTS.md plus every doc under `docs/`, sorted for stable output."""
    found: list[pathlib.Path] = []
    root = repo_path / AGENTS_FILENAME
    if root.is_file():
        found.append(root)
    docs_dir = repo_path / "docs"
    if docs_dir.is_dir():
        found.extend(sorted(p for p in docs_dir.rglob("*.md") if p.is_file()))
    return found


def audit_repo(repo_path: pathlib.Path, rules: AgentsMdRules) -> AuditResult:
    """Run every deterministic check over one repo and apply its waivers."""
    repo_path = repo_path.resolve()
    result = AuditResult(repo=repo_path.name)
    agents = repo_path / AGENTS_FILENAME

    if not agents.is_file():
        result.findings.append(
            Finding(
                check="required-content",
                severity=Severity.ERROR,
                path=AGENTS_FILENAME,
                message="No AGENTS.md. Every managed repo needs one, however short.",
            )
        )
        return result

    text = agents.read_text(encoding="utf-8")
    docs = _markdown_files(repo_path)

    raw: list[Finding] = [
        *check_root_size(text, rules),
        *check_duplicate_headings(text),
        *check_pointers(repo_path, docs),
        *check_docs_orphans(repo_path, docs),
        *check_docs_index(repo_path, rules),
        *check_folder_index(repo_path),
        *check_code_blocks(repo_path, docs, rules),
        *check_claude_md(repo_path, rules),
        *check_bespoke_agent_files(repo_path, rules),
        *check_required_content(text, rules),
        *check_generation_markers(text),
    ]
    if rules.check_paths:
        raw.extend(check_path_liveness(repo_path, text))

    waiver_file = load_waivers(repo_path)
    today = dt.datetime.now().astimezone().date()
    active = {w.key for w in waiver_file.waivers if w.reason.strip() and not w.expired_on(today)}

    for finding in raw:
        (result.suppressed if finding.key in active else result.findings).append(finding)

    result.findings.extend(_waiver_findings(repo_path, waiver_file.waivers, {f.key for f in raw}))
    result.metrics = collect_metrics(text)
    return result
