"""Audit `AGENTS.md` and the docs tree against `docs/agents/agent-consistency.md`.

Only the rules a machine can decide live here. Whether an instruction *belongs*
in the root file, whether it is vague, and whether two instructions contradict
each other are judgement calls — `docs/agents/agents-md-governance.md` records why those
are reported to an agent rather than gated.

Every finding carries a stable `check:path` key, and a repo may dismiss one by
committing a waiver to `.agents-audit.json`. Waivers require a reason, may
expire, and are themselves reported once the finding they suppress stops
occurring — otherwise the waiver file becomes the ball of mud the rules exist to
prevent.
"""

from __future__ import annotations

import datetime as dt
import pathlib
import re
from collections.abc import Iterable, Sequence
from enum import StrEnum
from urllib.parse import unquote

from pydantic import BaseModel, Field

from rig import proc
from rig.repo_governance.policy_config import AgentsMdRules

WAIVER_FILENAME = ".agents-audit.json"
AGENTS_FILENAME = "AGENTS.md"

#: Checks that fail an audit. Report-only metrics are listed separately so that
#: `--json` consumers can tell a gate from an observation.
GATING_CHECKS: tuple[str, ...] = (
    "root-size",
    "duplicate-heading",
    "pointer-integrity",
    "docs-orphan",
    "claude-md-shape",
    "bespoke-agent-file",
    "path-liveness",
    "required-content",
    "generation-marker",
    "docs-index",
    "folder-index",
    "docs-code-block",
)

REPORT_ONLY_CHECKS: tuple[str, ...] = (
    "instruction-count",
    "forcing-language",
    "section-outlier",
)

_PACKAGE_MANAGERS = ("pnpm", "npm", "yarn", "bun", "uv", "poetry", "pip", "cargo", "dotnet", "go ")
_GENERATION_MARKERS = ("<!-- generated", "auto-generated", "do not edit — generated", "generated by")
_FORCING = re.compile(r"\b(MUST|NEVER|ALWAYS|REQUIRED)\b")
_MD_LINK = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
_HEADING = re.compile(r"^(#{2,3})\s+(.*?)\s*$")
_BACKTICKED = re.compile(r"`([^`\n]+)`")
_INSTRUCTION = re.compile(r"^\s*(?:\d+\.|[-*])\s+\S")
_FENCE = re.compile(r"^\s*(?:```|~~~)")
_CODE_SPAN = re.compile(r"`+[^`\n]+`+")


class Severity(StrEnum):
    """How a finding should be treated by a caller."""

    ERROR = "error"
    WARN = "warn"
    INFO = "info"


class Finding(BaseModel):
    """One thing the audit noticed, addressable by a waiver."""

    check: str
    severity: Severity
    path: str
    message: str
    line: int | None = None

    @property
    def key(self) -> str:
        """Stable identity for waiving — deliberately excludes the message.

        A waiver keyed on the message would stop applying the moment the wording
        of the check changed, which is how a suppression list silently reopens.
        """
        return f"{self.check}:{self.path}"


class Waiver(BaseModel):
    """A committed dismissal of one finding."""

    check: str
    path: str
    reason: str = ""
    expires: str | None = None

    @property
    def key(self) -> str:
        return f"{self.check}:{self.path}"

    def expired_on(self, today: dt.date) -> bool:
        """Return True if this waiver has lapsed. An unparseable date is lapsed."""
        if not self.expires:
            return False
        try:
            return dt.date.fromisoformat(self.expires) < today
        except ValueError:
            return True


def _no_waivers() -> list[Waiver]:
    """Typed factory — a bare ``list`` resolves as ``list[Unknown]``."""
    return []


def _no_findings() -> list[Finding]:
    """Typed factory — see `_no_waivers`."""
    return []


def _no_metrics() -> dict[str, int]:
    """Typed factory — see `_no_waivers`."""
    return {}


class WaiverFile(BaseModel):
    """The parsed `.agents-audit.json`."""

    waivers: list[Waiver] = Field(default_factory=_no_waivers)


class AuditResult(BaseModel):
    """Everything one repo's audit produced."""

    repo: str
    findings: list[Finding] = Field(default_factory=_no_findings)
    suppressed: list[Finding] = Field(default_factory=_no_findings)
    metrics: dict[str, int] = Field(default_factory=_no_metrics)

    @property
    def failed(self) -> bool:
        """True if any surviving finding is an error."""
        return any(f.severity is Severity.ERROR for f in self.findings)


