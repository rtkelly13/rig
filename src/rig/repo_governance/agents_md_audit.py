def load_waivers(repo_path: pathlib.Path) -> WaiverFile:
    """Read `.agents-audit.json`, returning an empty file when absent or invalid.

    A malformed waiver file is reported as a finding by `audit_repo` rather than
    raised here, so one bad edit cannot take the whole audit down.
    """
    path = repo_path / WAIVER_FILENAME
    if not path.is_file():
        return WaiverFile()
    try:
        return WaiverFile.model_validate_json(path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return WaiverFile()


def _waiver_findings(repo_path: pathlib.Path, waivers: Sequence[Waiver], keys_seen: set[str]) -> list[Finding]:
    """Report waivers that are unreasoned, lapsed, or no longer suppressing anything."""
    if not (repo_path / WAIVER_FILENAME).is_file():
        return []
    today = dt.datetime.now().astimezone().date()
    out: list[Finding] = []
    for waiver in waivers:
        if not waiver.reason.strip():
            out.append(
                Finding(
                    check="waiver-unreasoned",
                    severity=Severity.ERROR,
                    path=WAIVER_FILENAME,
                    message=f"Waiver for `{waiver.key}` has no reason. A dismissal without a reason is not reviewable.",
                )
            )
        if waiver.expired_on(today):
            out.append(
                Finding(
                    check="waiver-expired",
                    severity=Severity.WARN,
                    path=WAIVER_FILENAME,
                    message=f"Waiver for `{waiver.key}` expired on {waiver.expires} and no longer suppresses.",
                )
            )
        elif waiver.key not in keys_seen:
            out.append(
                Finding(
                    check="waiver-stale",
                    severity=Severity.INFO,
                    path=WAIVER_FILENAME,
                    message=f"Waiver for `{waiver.key}` suppresses nothing — the finding is fixed. Remove it.",
                )
            )
    return out


