def _load_frontmatter(path: Path) -> frontmatter.Post:
    return frontmatter.load(str(path))


def _blank_post() -> frontmatter.Post:
    return frontmatter.Post("")


@dataclass(frozen=True, slots=True)
class _LoadedNote:
    """A note's frontmatter and the lint codes it opts out of, or why it could not be read."""

    post: frontmatter.Post = field(default_factory=_blank_post)
    meta: NoteMeta = field(default_factory=NoteMeta)
    ignored_codes: frozenset[str] = frozenset()
    error: Exception | None = None


def _ignored_codes(value: object) -> frozenset[str]:
    items: list[object] = [value] if isinstance(value, str) else try_decode(list[object], value) or []
    return frozenset(text.upper() for text in (str(item).strip() for item in items) if text)


class VaultLinter:
    """Linter for Obsidian vault to find duplicates, broken links, and metadata issues."""

    # Required fields per note type. A type absent from this map is reported as
    # TVS005 "unknown type", so every type the vault actually uses must appear here
    # even when it requires nothing — otherwise valid notes are flagged as broken.
    TYPE_REQUIREMENTS: dict[str, list[str]] = {
        # Curated content
        "resource": ["source", "status", "created"],
        "resource-hub": ["status"],
        "social": ["source", "related_article", "status", "created"],
        # Structure
        "project": ["status", "created"],
        "project-note": ["status", "created"],
        "design-note": ["status", "created"],
        "area": ["status", "created"],
        # Journal. The largest single type in the vault; its notes are written by
        # hand and carry no source.
        "daily": ["created"],
        # Prose captured directly rather than from a link, so no `source` exists.
        "note": [],
        # Night Shift leftovers, still present in older notes.
        "task": ["status"],
        "spec": ["status"],
        # Open Knowledge Format concepts, generated by okf-sync. OKF requires only
        # `type`; the generator supplies the rest.
        "Repository": [],
        "Reference": [],
    }

    def __init__(self, vault_path: Path | None = None):
        self.vault_path: Path = vault_path or get_vault_path()

    def _should_lint_path(self, md_file: Path) -> bool:
        rel_str = str(md_file.relative_to(self.vault_path))
        if ".git" in str(md_file) or ".obsidian" in str(md_file) or "Archive" in str(md_file):
            return False
        return any(x in rel_str for x in ["Resources", "Social Media Posts", "Areas", "Projects"])

    def _is_hub_like_filename(self, md_file: Path) -> bool:
        rel_path = md_file.relative_to(self.vault_path)
        stem = md_file.stem
        parent = md_file.parent.name
        return (
            stem in ["Resources", "Areas", "Projects", "Archive"]
            or "Index" in stem
            or "Hub" in stem
            or stem.startswith("Inbox-")
            or parent == stem
            or parent + " Index" == stem
            or (len(rel_path.parts) == 2 and rel_path.parts[0] in ["Resources", "Areas", "Projects"])
        )

    def _load_note(self, md_file: Path) -> _LoadedNote:
        try:
            post = _load_frontmatter(md_file)
        except FRONTMATTER_ERRORS as exc:
            return _LoadedNote(error=exc)
        meta = read_note_meta(post.metadata)
        return _LoadedNote(post, meta, _ignored_codes(meta.lint_ignore or meta.lint_ignore_kebab))

    def _is_ignored(self, ignored_codes: frozenset[str], code: str) -> bool:
        return code.upper() in ignored_codes or "ALL" in ignored_codes or "TVS" in ignored_codes

    def _build_metadata_failure(self, path: Path, code: str, reason: str, severity: str) -> MetadataFailure:
        return MetadataFailure(path=path, code=code, reason=reason, severity=severity)

    def _folder_stats_for(self, folder_stats: dict[str, FolderLintStats], key: str) -> FolderLintStats:
        stats = folder_stats.get(key)
        if stats is None:
            stats = FolderLintStats()
            folder_stats[key] = stats
        return stats

    def _append_filename_issue(
        self,
        issues: list[FilenameIssue],
        ignored_codes: frozenset[str],
        *,
        path: Path,
        code: str,
        reason: str,
        severity: str,
        suggested_stem: str,
        suggested_path: Path,
    ) -> None:
        if self._is_ignored(ignored_codes, code):
            return
        issues.append(
            FilenameIssue(
                path=path,
                code=code,
                reason=reason,
                severity=severity,
                suggested_stem=suggested_stem,
                suggested_path=suggested_path,
            )
        )

    def _filename_reason(self, path: Path, suggested_stem: str) -> str:
        relative_path = path.relative_to(self.vault_path)
        return ", ".join(
            spec.reason for spec in filename_issue_specs(path.stem, suggested_stem, relative_path=relative_path)
        )

    def find_filename_issues(self) -> list[FilenameIssue]:
        """Flag filenames that should be renamed to cleaner, stable slugs."""
        issues: list[FilenameIssue] = []
        for md_file in self.vault_path.rglob("*.md"):
            if not self._should_lint_path(md_file):
                continue
            if self._is_hub_like_filename(md_file):
                continue

            note = self._load_note(md_file)
            meta, ignored_codes = note.meta, note.ignored_codes
            if note.error is not None:
                logger.error(f"Error inspecting filename for {md_file}: {note.error}")
                continue
            relative_path = md_file.relative_to(self.vault_path)
            portability_reason = windows_portability_issue_reason(relative_path)
            suggested_stem = suggest_clean_filename_stem(
                md_file.stem,
                title=meta.title or "",
                source_url=meta.source or meta.url or "",
                related_article=meta.related_article or "",
            )
            if portability_reason is not None:
                suggested_stem = portable_windows_stem(suggested_stem or md_file.stem)
            if not suggested_stem:
                continue
            if not needs_filename_cleanup(md_file.stem, relative_path=relative_path):
                continue
            if suggested_stem == md_file.stem and portability_reason is None:
                continue

            suggested_path = md_file.with_name(f"{suggested_stem}{md_file.suffix}")
            for spec in filename_issue_specs(
                md_file.stem,
                suggested_stem,
                relative_path=relative_path,
            ):
                self._append_filename_issue(
                    issues,
                    ignored_codes,
                    path=md_file,
                    code=spec.code,
                    reason=spec.reason,
                    severity=spec.severity,
                    suggested_stem=suggested_stem,
                    suggested_path=suggested_path,
                )
        deduped: dict[Path, dict[str, FilenameIssue]] = {}
        for issue in issues:
            deduped.setdefault(issue.path, {})[issue.code] = issue
        unique = [issue for by_code in deduped.values() for issue in by_code.values()]
        return sorted(unique, key=lambda item: (str(item.path), item.code))

    def _rewrite_wikilinks_in_text(self, content: str, old_path: Path, new_path: Path) -> str:
        old_rel = old_path.relative_to(self.vault_path).as_posix()
        new_rel = new_path.relative_to(self.vault_path).as_posix()
        old_rel_noext = old_rel.removesuffix(old_path.suffix)
        new_rel_noext = new_rel.removesuffix(new_path.suffix)
        old_targets = {old_path.name, old_path.stem, old_rel, old_rel_noext}

        def replace(match: re.Match[str]) -> str:
            prefix, target, alias, suffix = match.groups()
            cleaned_target = target.strip()
            if cleaned_target not in old_targets:
                return match.group(0)

            if "/" in cleaned_target:
                replacement = new_rel if cleaned_target.endswith(".md") else new_rel_noext
            else:
                replacement = new_path.name if cleaned_target.endswith(".md") else new_path.stem
            return f"{prefix}{replacement}{alias or ''}{suffix}"

        return re.sub(r"(!?\[\[)([^\]|]+)(\|[^\]]+)?(\]\])", replace, content)

    def _update_wikilink_references(self, old_path: Path, new_path: Path) -> int:
        updated = 0
        for md_file in self.vault_path.rglob("*.md"):
            if ".git" in str(md_file) or ".obsidian" in str(md_file):
                continue
            try:
                content = md_file.read_text(encoding="utf-8")
                new_content = self._rewrite_wikilinks_in_text(content, old_path, new_path)
                if new_content != content:
                    md_file.write_text(new_content, encoding="utf-8")
                    updated += 1
            except (OSError, UnicodeError) as e:
                logger.error(f"Error updating links in {md_file}: {e}")
        return updated

    def cleanup_filenames(self, dry_run: bool = True):
        """Rename pre-existing notes with ugly filenames and update wikilinks."""
        issue_map: dict[Path, FilenameIssue] = {}
        for issue in self.find_filename_issues():
            issue_map.setdefault(issue.path, issue)
        issues = list(issue_map.values())
        renamed = 0
        skipped = 0

        for issue in issues:
            path = issue.path
            target = issue.suggested_path
            if not path.exists():
                skipped += 1
                continue
            if target.exists() and target.resolve() != path.resolve():
                console.print(
                    f"[yellow]Skipping rename:[/yellow] {path.relative_to(self.vault_path)} -> "
                    f"{target.relative_to(self.vault_path)} (target exists)"
                )
                skipped += 1
                continue

            if dry_run:
                console.print(
                    f"[dim](Dry Run) Would rename:[/dim] {path.relative_to(self.vault_path)} -> "
                    f"{target.relative_to(self.vault_path)}"
                )
                renamed += 1
                continue

            path.rename(target)
            updated_refs = self._update_wikilink_references(path, target)
            console.print(
                f"[green]✓ Renamed:[/green] {path.relative_to(self.vault_path)} -> "
                f"{target.relative_to(self.vault_path)} [dim]({updated_refs} files updated)[/dim]"
            )
            renamed += 1

        mode = "Renamed" if not dry_run else "Found"
        console.print(f"\n[bold]{mode} {renamed} filename issues.[/bold]")
        if skipped:
            console.print(f"[yellow]Skipped {skipped} filename issues due to conflicts or missing files.[/yellow]")

    def find_metadata_failures(self) -> list[MetadataFailure]:
        """Find notes missing required metadata based on their 'type'."""
        failures: list[MetadataFailure] = []
        for md_file in self.vault_path.rglob("*.md"):
            if not self._should_lint_path(md_file):
                continue

            note = self._load_note(md_file)
            post, ignored_codes, exc = note.post, note.ignored_codes, note.error
            if exc is not None:
                failures.append(
                    self._build_metadata_failure(
                        md_file,
                        LINT_INVALID_FRONTMATTER,
                        f"Invalid frontmatter: {exc}",
                        "error",
                    )
                )
                continue
            note_type = note.meta.type

            if not note_type:
                suggested = suggested_type(md_file.relative_to(self.vault_path))
                if not self._is_ignored(ignored_codes, LINT_MISSING_TYPE):
                    failures.append(
                        self._build_metadata_failure(
                            md_file,
                            LINT_MISSING_TYPE,
                            f"Missing 'type' field (Suggested: '{suggested}')",
                            "error",
                        )
                    )
                continue

            if note_type in self.TYPE_REQUIREMENTS:
                for field in self.TYPE_REQUIREMENTS[note_type]:
                    val = post.get(field)
                    code = ""
                    reason = ""
                    if val is None:
                        code = LINT_MISSING_REQUIRED_FIELD
                        reason = f"Type '{note_type}' missing required field: '{field}'"
                    elif isinstance(val, str) and not val.strip():
                        code = LINT_EMPTY_REQUIRED_FIELD
                        reason = f"Type '{note_type}' has empty field: '{field}'"
                    elif isinstance(val, list) and not val:
                        code = LINT_EMPTY_REQUIRED_LIST
                        reason = f"Type '{note_type}' has empty list: '{field}'"

                    if not code:
                        continue
                    if field == "source" and note_type in ["resource-hub", "area", "project"]:
                        continue
                    if self._is_ignored(ignored_codes, code):
                        continue
                    failures.append(self._build_metadata_failure(md_file, code, reason, "error"))
            elif not self._is_ignored(ignored_codes, LINT_UNKNOWN_TYPE):
                failures.append(
                    self._build_metadata_failure(
                        md_file,
                        LINT_UNKNOWN_TYPE,
                        f"Unknown note type: '{note_type}'",
                        "warning",
                    )
                )
        return failures

    def backfill_types(self, dry_run: bool = True):
        """Automatically add 'type' to notes based on their folder."""
        count = 0
        for md_file in self.vault_path.rglob("*.md"):
            if ".git" in str(md_file) or ".obsidian" in str(md_file) or "Archive" in str(md_file):
                continue

            suggested = suggested_type(md_file.relative_to(self.vault_path))
            if not suggested:
                continue

            try:
                post = _load_frontmatter(md_file)
                current_type = read_note_meta(post.metadata).type

                needs_update = (
                    not current_type
                    or current_type in ["note", "project"]
                    or (current_type == "resource" and suggested in ["resource-hub"])
                    or (current_type in ["project", "resource"] and suggested in ["project-note", "design-note"])
                )

                if needs_update:
                    if dry_run:
                        console.print(
                            "[dim](Dry Run) Would update type from "
                            f"'{current_type}' to '{suggested}' for: {md_file.name}[/dim]"
                        )
                    else:
                        post.metadata["type"] = suggested
                        md_file.write_text(dump_frontmatter(post), encoding="utf-8")
                        console.print(f"[green]✓ Updated type to '{suggested}':[/green] {md_file.name}")
                    count += 1
            except FRONTMATTER_ERRORS as e:
                logger.error(f"Error backfilling {md_file}: {e}")

        mode = "Found" if dry_run else "Fixed"
        console.print(f"\n[bold]{mode} {count} notes missing 'type'.[/bold]")

    def repair_metadata(self, dry_run: bool = True):
        """Intelligent metadata repair for all notes in PARA roots."""
        count = 0
        for md_file in self.vault_path.rglob("*.md"):
            if not self._should_lint_path(md_file):
                continue

            rel_str = str(md_file.relative_to(self.vault_path))

            try:
                content = md_file.read_text(encoding="utf-8")
                post = frontmatter.loads(content)
                orig_metadata = post.metadata.copy()

                # Helper to check if a field is functionally empty
                def is_field_empty(post: frontmatter.Post, f: str) -> bool:
                    v = post.get(f)
                    if v is None:
                        return True
                    if isinstance(v, str) and not v.strip():
                        return True
                    return bool(isinstance(v, list) and not v)

                # 1. Backfill or Refine 'type'
                meta = read_note_meta(post.metadata)
                note_type = meta.type
                suggested = suggested_type(md_file.relative_to(self.vault_path))

                if not note_type or note_type == "note":
                    post.metadata["type"] = suggested
                    note_type = suggested

                # 2. Backfill 'status' and 'created' (Common for all)
                if is_field_empty(post, "status"):
                    post.metadata["status"] = "active"
                if is_field_empty(post, "created"):
                    mtime = md_file.stat().st_mtime
                    post.metadata["created"] = time.strftime("%Y-%m-%d %H:%M", time.localtime(mtime))

                # 3. Type-specific repairs
                # 3a. Extract Source
                has_url_in_body = False
                source_match = re.search(r"Source:\s*(https?://[^\s\)]+)", content, re.I)
                if not source_match:
                    source_match = re.search(r"^(?:- )?(https?://[^\s\)]+)", content, re.M)

                if source_match:
                    has_url_in_body = True
                    if note_type == "resource" and is_field_empty(post, "source"):
                        post.metadata["source"] = source_match.group(1)

                # 3b. Hub Refinement (If no source found and no URL in body, it's likely a hub)
                if (
                    note_type == "resource"
                    and is_field_empty(post, "source")
                    and not has_url_in_body
                    and "Resources" in rel_str
                ):
                    post.metadata["type"] = "resource-hub"
                    note_type = "resource-hub"

                # 3c. Social Source Restoration
                if note_type == "social" and is_field_empty(post, "source"):
                    article = meta.related_article
                    if article:
                        article_name = re.sub(r"\[\[(.*?)\]\]", r"\1", article).replace(".md", "").strip()
                        for res_file in (self.vault_path / "Resources").rglob("*.md"):
                            if res_file.stem == article_name:
                                resource_source = read_note_meta(_load_frontmatter(res_file).metadata).source
                                if resource_source:
                                    post.metadata["source"] = resource_source
                                    break

                # 4. Save if changed
                if post.metadata != orig_metadata:
                    if dry_run:
                        console.print(f"[dim](Dry Run) Would repair metadata for: {md_file.name}[/dim]")
                    else:
                        md_file.write_text(dump_frontmatter(post), encoding="utf-8")
                        console.print(f"[green]✓ Repaired metadata for:[/green] {md_file.name}")
                    count += 1

            except FRONTMATTER_ERRORS as e:
                logger.error(f"Error repairing {md_file}: {e}")

        mode = "Found" if dry_run else "Repaired"
        console.print(f"\n[bold]{mode} {count} notes with metadata issues.[/bold]")

    def find_duplicates(self) -> dict[str, list[Path]]:
        """Notes sharing a source URL or title; see `lint_duplicates.find_duplicates`."""
        return find_duplicates(self.vault_path)

    def get_duplicate_failures(self) -> list[MetadataFailure]:
        failures: list[MetadataFailure] = []
        for key, files in self.find_duplicates().items():
            for path in files:
                failures.append(
                    self._build_metadata_failure(
                        path,
                        LINT_DUPLICATE_NOTE,
                        f"Duplicate note group: {key}",
                        "error",
                    )
                )
        return failures

    def cleanup_social_duplicates(self, dry_run: bool = True):
        """Ensure Social Media Posts correctly link to their parent Resources."""
        duplicates = self.find_duplicates()

        for url, files in duplicates.items():
            resources = [f for f in files if "Resources" in str(f)]
            social_posts = [f for f in files if "Social Media Posts" in str(f)]

            if resources and social_posts:
                console.print(f"\n[bold yellow]Repairing Social Linking for:[/bold yellow] {url}")
                winner = resources[0]

                for sp in social_posts:
                    if dry_run:
                        console.print(
                            f"  [dim](Dry Run) Would update social link in {sp.name} to point to {winner.name}[/dim]"
                        )
                    else:
                        post = _load_frontmatter(sp)
                        post.metadata["related_article"] = f"[[{winner.name}]]"
                        sp.write_text(dump_frontmatter(post), encoding="utf-8")
                        console.print(f"  [green]✓ Repaired social linking in {sp.name}[/green]")

    def cleanup_resource_duplicates(self, dry_run: bool = True):
        """Find and remove redundant Resource notes for the same URL."""
        duplicates = self.find_duplicates()

        for url, files in duplicates.items():
            resources = [f for f in files if "Resources" in str(f)]
            if len(resources) <= 1:
                continue

            console.print(f"\n[bold yellow]Consolidating Resources for:[/bold yellow] {url}")
            scored_files: list[ScoredDuplicate] = []
            for f in resources:
                if not f.exists():
                    continue
                content = f.read_text(encoding="utf-8")
                word_count = len(re.findall(r"\w+", content))
                name_penalty = 1000 if "(1)" in f.name else 0
                folder_bonus = 50 if "Inbox-Resources" not in str(f) else 0
                score = word_count + folder_bonus - name_penalty
                scored_files.append(ScoredDuplicate(path=f, score=score))

            if not scored_files:
                continue

            scored_files.sort(key=lambda item: item.score, reverse=True)
            best = scored_files[0]
            winner = best.path
            losers = [x.path for x in scored_files[1:]]

            console.print(f"  [green]Winner:[/green] {winner.relative_to(self.vault_path)} (Score: {best.score})")

            for loser in losers:
                if not loser.exists():
                    continue
                if dry_run:
                    console.print(
                        f"  [red](Dry Run) Would archive duplicate:[/red] {loser.relative_to(self.vault_path)}"
                    )
                else:
                    archive_root = self.vault_path / "Archive" / "Duplicates"
                    archive_root.mkdir(parents=True, exist_ok=True)
                    target = archive_root / loser.name
                    if target.exists():
                        target = target.with_stem(f"{target.stem}-{int(time.time())}")
                    loser.rename(target)
                    console.print(f"  [red]✓ Archived:[/red] {loser.name}")

    def get_folder_lint_stats(self) -> dict[str, FolderLintStats]:
        """Aggregate linting failures by folder to calculate health scores."""
        metadata_failures = self.find_metadata_failures()
        filename_issues = self.find_filename_issues()
        duplicate_failures = self.get_duplicate_failures()

        folder_stats: dict[str, FolderLintStats] = {}

        # Helper to get folder key
        def get_key(p: Path) -> str:
            try:
                rel = p.relative_to(self.vault_path)
                if len(rel.parts) > 1:
                    return str(rel.parent)
                return rel.parts[0] if rel.parts else "Unknown"
            except ValueError:
                return "Unknown"

        # 1. Process metadata failures
        for fail in metadata_failures:
            key = get_key(fail.path)
            stats = self._folder_stats_for(folder_stats, key)
            if fail.severity == "warning":
                stats.metadata_warnings += 1
            else:
                stats.metadata_errors += 1

        # 1b. Process filename issues
        for issue in filename_issues:
            key = get_key(issue.path)
            stats = self._folder_stats_for(folder_stats, key)
            stats.filename_issues += 1

        # 2. Process duplicates
        for dup in duplicate_failures:
            key = get_key(dup.path)
            stats = self._folder_stats_for(folder_stats, key)
            stats.duplicates += 1

        # 3. Count total notes per folder
        for md_file in self.vault_path.rglob("*.md"):
            if ".git" in str(md_file) or "Archive" in str(md_file):
                continue
            key = get_key(md_file)
            stats = self._folder_stats_for(folder_stats, key)
            stats.total_notes += 1

        # 4. Calculate Scores (0-100, where 100 is perfect)
        for stats in folder_stats.values():
            stats.rescore()

        return folder_stats

    def run_lint(self):
        """Run all linting checks."""
        metadata_failures = self.find_metadata_failures()
        metadata_errors = [item for item in metadata_failures if item.severity == "error"]
        metadata_warnings = [item for item in metadata_failures if item.severity == "warning"]
        filename_issues = self.find_filename_issues()
        duplicates = self.find_duplicates()

        success = True
        if metadata_errors:
            console.print(f"[bold red]Found {len(metadata_errors)} metadata errors:[/bold red]")
            for fail in metadata_errors:
                console.print(f"  - [red]{fail.code}[/red] {fail.reason}: {fail.path.name}")
            success = False

        if metadata_warnings:
            console.print(f"\n[bold yellow]Found {len(metadata_warnings)} metadata warnings:[/bold yellow]")
            for fail in metadata_warnings:
                console.print(f"  - [yellow]{fail.code}[/yellow] {fail.reason}: {fail.path.name}")

        if filename_issues:
            grouped_filename_issues: dict[Path, list[FilenameIssue]] = {}
            for issue in filename_issues:
                grouped_filename_issues.setdefault(issue.path, []).append(issue)

            console.print(f"\n[bold yellow]Found {len(filename_issues)} filename issues:[/bold yellow]")
            for path, issue_group in grouped_filename_issues.items():
                issue = issue_group[0]
                codes = ", ".join(item.code for item in issue_group)
                rel_path = issue.path.relative_to(self.vault_path)
                console.print(
                    "  - "
                    f"[yellow]{codes}[/yellow] {rel_path}: "
                    f"{self._filename_reason(path, issue.suggested_stem)} -> "
                    f"suggest [cyan]{issue.suggested_path.name}[/cyan]"
                )

        if duplicates:
            console.print(f"\n[bold red]Found {len(duplicates)} duplicate groups (excluding genuine links):[/bold red]")
            for key, files in duplicates.items():
                console.print(f"\n[yellow]{key}[/yellow]")
                for f in files:
                    console.print(f"  - {f.relative_to(self.vault_path)}")
            success = False

        if success:
            console.print("[green]✓ Vault is clean. (Required metadata present, no duplicates detected).[/green]")
        return success

    def _report_item(self, failure: MetadataFailure) -> MetadataReportItem:
        return MetadataReportItem(
            path=failure.path.relative_to(self.vault_path).as_posix(),
            code=failure.code,
            reason=failure.reason,
            severity=failure.severity,
        )

    def lint_report(self) -> LintReport:
        metadata_failures = self.find_metadata_failures()
        metadata_errors = [item for item in metadata_failures if item.severity == "error"]
        metadata_warnings = [item for item in metadata_failures if item.severity == "warning"]
        filename_issues = self.find_filename_issues()
        duplicates = self.find_duplicates()

        grouped_filename_issues: dict[str, FilenameReport] = {}
        for issue in filename_issues:
            rel_path = issue.path.relative_to(self.vault_path).as_posix()
            grouped = grouped_filename_issues.get(rel_path)
            if grouped is None:
                grouped = grouped_filename_issues[rel_path] = FilenameReport(
                    path=rel_path,
                    severity=issue.severity,
                    reason=self._filename_reason(issue.path, issue.suggested_stem),
                    suggested_path=issue.suggested_path.relative_to(self.vault_path).as_posix(),
                )
            grouped.codes.append(issue.code)

        return LintReport(
            ok=len(metadata_errors) == 0 and len(duplicates) == 0,
            vault_path=str(self.vault_path),
            metadata=MetadataReport(
                errors=tuple(self._report_item(item) for item in metadata_errors),
                warnings=tuple(self._report_item(item) for item in metadata_warnings),
            ),
            filenames=tuple(sorted(grouped_filename_issues.values(), key=lambda item: item.path)),
            duplicates={
                key: [path.relative_to(self.vault_path).as_posix() for path in files]
                for key, files in duplicates.items()
            },
        )


def run_vault_lint(vault_path: Path | None = None, *, json_output: bool = False):
    linter = VaultLinter(vault_path)
    if json_output:
        report = linter.lint_report()
        console.print_json(json.dumps(asdict(report), default=str))
        return report.ok
    return linter.run_lint()
