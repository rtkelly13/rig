"""Deterministic Markdown projection and offline, strictly read-only verification."""

from __future__ import annotations

import html
import re
from datetime import datetime
from pathlib import Path

from rig.github_prs import PrRef
from rig.triage.models import Entry, Item, rank

BEGIN = "<!-- rig-triage:begin v1 -->"
END = "<!-- rig-triage:end -->"
HEADER = "| Rank | Kind | Reference | Title | Priority | Readiness | Lines | Created | Head |"
DIVIDER = "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"
READINESS = ("clean", "behind", "blocked", "draft-or-unknown")


def _text(value: str) -> str:
    return html.escape(" ".join(value.split())).replace("|", "&#124;")


def render(items: list[Item]) -> str:
    """Stable bytes for identical snapshots; no runtime timestamp or live calls."""
    lines = [BEGIN, HEADER, DIVIDER]
    for kind in ("pr", "issue"):
        group = sorted((item for item in items if item.kind == kind), key=rank)
        for index, item in enumerate(group, 1):
            priority = f"P{item.priority}" if item.priority < 4 else "unlabelled"
            ready = READINESS[item.readiness] if kind == "pr" else "n/a"
            lines.append(
                f"| {index} | {kind} | [{item.ref}]({item.url}) | {_text(item.title)} | {priority} | "
                f"{ready} | {item.lines} | {item.created} | {item.head or '-'} |"
            )
    return "\n".join([*lines, END])


def _block(text: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError("Expected exactly one v1 triage begin/end block")
    start, end = text.index(BEGIN), text.index(END)
    if end < start:
        raise ValueError("Triage markers are reversed")
    return text[start : end + len(END)]


def verify(text: str) -> None:
    """Validate shape, references, ranking and duplicates without GitHub, DB or writes."""
    block = _block(text)
    rows = block.splitlines()
    if rows[:3] != [BEGIN, HEADER, DIVIDER]:
        raise ValueError("Invalid triage table header")
    items: list[Item] = []
    refs: set[str] = set()
    for line in rows[3:-1]:
        cells = [cell.strip() for cell in line.split("|")]
        if len(cells) != 11 or cells[0] or cells[-1]:
            raise ValueError("Each triage row must have nine columns")
        _, position, kind, link, title, priority, ready, size, created, head, _ = cells
        if kind not in ("pr", "issue") or not position.isdecimal() or int(position) < 1:
            raise ValueError("Invalid kind or rank")
        match = re.fullmatch(r"\[([^\]]+)\]\(([^)]+)\)", link)
        if match is None:
            raise ValueError("Expected a GitHub reference link")
        ref = PrRef.parse(match[1])
        if str(ref) in refs:
            raise ValueError(f"Duplicate item: {ref}")
        refs.add(str(ref))
        if priority not in ("P0", "P1", "P2", "P3", "unlabelled"):
            raise ValueError("Invalid priority")
        if not size.isdecimal() or not title or datetime.fromisoformat(created).tzinfo is None:
            raise ValueError("Invalid size, title or creation time")
        if (kind == "pr" and ready not in READINESS) or (kind == "issue" and ready != "n/a"):
            raise ValueError("Invalid readiness")
        if (kind == "pr" and re.fullmatch(r"[0-9a-f]{40}", head) is None) or (kind == "issue" and head != "-"):
            raise ValueError("Invalid head commit")
        item = Item(
            ref.slug,
            ref.number,
            kind,
            html.unescape(title),
            "OPEN",
            created,
            created,
            "" if head == "-" else head,
            4 if priority == "unlabelled" else int(priority[-1]),
            READINESS.index(ready) if kind == "pr" else 0,
            int(size),
        )
        if match[2] != item.url:
            raise ValueError("Reference URL does not match the item")
        items.append(item)
    if render(items) != block:
        raise ValueError("Queue is not in canonical priority/readiness/size/age order or has invalid ranks")


def export(path: Path, entries: list[Entry]) -> None:
    """Replace only the generated block; preserve surrounding human process notes."""
    items = [
        entry.item
        for entry in entries
        if entry.item.in_scope and entry.item.state == "OPEN" and not entry.deferred and not entry.archived
    ]
    block = render(items)
    if path.exists():
        old = path.read_text(encoding="utf-8")
        previous = _block(old)
        content = old.replace(previous, block, 1)
    else:
        content = (
            "# PR and Issue Triage Queue\n\n"
            "Transient projection generated by rig; regenerate rather than commit or file in the vault.\n\n"
            "Priority → readiness → changed lines → creation time → repository → number.\n"
            "PRs precede the issue queue. Deferred and closed items remain in rig's history.\n\n" + block + "\n"
        )
    verify(content)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    # Same-directory replace prevents readers seeing a partial Markdown table.
    pending = path.with_suffix(".md.pending")
    try:
        pending.write_text(content, encoding="utf-8")
        pending.replace(path)
    finally:
        pending.unlink(missing_ok=True)
