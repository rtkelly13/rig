"""Tests for the Tailwind-compiled gallery stylesheet.

`gallery.css` is generated by `pnpm css:build` from `styles/gallery.src.css` and
committed, because the Python CLI inlines it into a self-contained preview.html
and must work without Node installed. That means it can go stale, so these tests
check the committed artefact still covers what the templates ask for.

`pnpm css:check` is the exact verification (it rebuilds and compares); these
tests are the version that runs without Node.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from rig.image_drift.cli_base import TEMPLATE_DIR

pytestmark = pytest.mark.ci

REPO_ROOT = Path(__file__).resolve().parents[1]
COMPILED = TEMPLATE_DIR / "gallery.css"
SOURCE = REPO_ROOT / "styles" / "gallery.src.css"

# Component utilities defined with @utility in the source and used by name in the
# templates. Tailwind only emits these if the source still declares them.
COMPONENTS = (
    "panel",
    "card-shadow",
    "section-title",
    "badge-good",
    "badge-warn",
    "badge-bad",
    "badge-ref",
    "ribbon",
    "crop-tile",
    "scroll-x",
)

# @theme tokens the templates reference as colour utilities.
TOKENS = (
    "--color-ink",
    "--color-panel",
    "--color-edge",
    "--color-accent",
    "--color-magenta",
    "--color-muted",
    "--color-good",
)


def test_compiled_stylesheet_is_committed() -> None:
    """The CLI inlines this file, so it must exist without a Node toolchain."""
    assert COMPILED.exists()
    assert COMPILED.stat().st_size > 5_000


def test_compiled_stylesheet_is_tailwind_output() -> None:
    assert COMPILED.read_text(encoding="utf-8").lstrip().startswith("/*! tailwindcss")


def test_source_configures_tailwind_in_css_not_javascript() -> None:
    """Tailwind v4 is configured in CSS; a JS config file would be a regression."""
    source = SOURCE.read_text(encoding="utf-8")
    assert '@import "tailwindcss"' in source
    assert "@theme" in source
    assert not (REPO_ROOT / "tailwind.config.js").exists()
    assert not (REPO_ROOT / "tailwind.config.ts").exists()


def test_source_points_tailwind_at_the_templates() -> None:
    """Without an explicit @source the utilities used in .jinja are never emitted."""
    assert "@source" in SOURCE.read_text(encoding="utf-8")
    assert ".jinja" in SOURCE.read_text(encoding="utf-8")


@pytest.mark.parametrize("component", COMPONENTS)
def test_component_utility_is_emitted(component: str) -> None:
    assert f".{component}" in COMPILED.read_text(encoding="utf-8")


@pytest.mark.parametrize("token", TOKENS)
def test_theme_token_is_emitted(token: str) -> None:
    assert token in COMPILED.read_text(encoding="utf-8")


def test_every_component_class_used_in_templates_is_compiled() -> None:
    """Catches the common staleness case: a template gains a component class but
    nobody re-ran the build."""
    compiled = COMPILED.read_text(encoding="utf-8")
    used: set[str] = set()
    for template in TEMPLATE_DIR.glob("*.jinja"):
        for attribute in re.findall(r'class="([^"]*)"', template.read_text(encoding="utf-8")):
            # Skip Jinja expressions; those resolve at render time.
            for name in attribute.split():
                if "{" not in name and name in COMPONENTS:
                    used.add(name)
    assert used, "expected the templates to use the component utilities"
    missing = sorted(name for name in used if f".{name}" not in compiled)
    assert not missing, f"not in the compiled CSS - run `pnpm css:build`: {missing}"


def test_no_handwritten_css_remains_in_templates() -> None:
    """Styling belongs in Tailwind, not in per-template <style> blocks."""
    for template in TEMPLATE_DIR.glob("*.jinja"):
        text = template.read_text(encoding="utf-8")
        if template.name == "base.html.jinja":
            # base holds the single <style> that inlines the compiled sheet.
            assert '{% include "gallery.css" %}' in text
            continue
        assert "<style" not in text
        assert "style=" not in text


def test_package_manifest_pins_pnpm_and_tailwind_four() -> None:
    manifest = (REPO_ROOT / "package.json").read_text(encoding="utf-8")
    assert '"packageManager": "pnpm@' in manifest
    assert '"tailwindcss": "^4' in manifest
    assert (REPO_ROOT / "pnpm-lock.yaml").exists()


def test_tailwind_does_not_scan_python_sources() -> None:
    """Prose in a Python module must not be able to add CSS utilities.

    gallery.css is committed and byte-compared by `pnpm css:check`. Scanning a
    .py file for class names means its docstrings feed the stylesheet: the word
    "fixed" in an unrelated CLI docstring once added `.fixed{position:fixed}`
    and turned CI red. Runtime class names are safelisted by name instead.
    """
    source = SOURCE.read_text(encoding="utf-8")
    scanned = re.findall(r'@source\s+"([^"]+)"', source)
    assert not [s for s in scanned if s.endswith(".py")], (
        f"gallery.src.css scans Python sources {scanned}; safelist the class names with "
        "@source inline(...) instead so prose cannot leak into the stylesheet."
    )


def test_runtime_badge_classes_are_compiled() -> None:
    """The safelist must still cover every class `_badge_class` can return."""
    compiled = COMPILED.read_text(encoding="utf-8")
    for name in ("badge-good", "badge-warn", "badge-bad"):
        assert f".{name}{{" in compiled, f"{name} missing from gallery.css; check the @source inline safelist"
