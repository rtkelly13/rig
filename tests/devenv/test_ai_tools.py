def _written(merge: SettingsMerge):
    """The merged settings as they land on disk."""
    return json.loads(json.dumps(merge.settings))


@pytest.mark.ci
def test_claude_code_union_merge():
    # Existing settings with custom preference and custom allow item
    existing = {
        "model": "claude-3-5-sonnet",
        "permissions": {
            "allow": ["Bash(my_custom_script:*)"],
            "defaultMode": "dontAcceptEdits",
        },
    }

    merge = merge_claude_settings(existing)
    settings = _written(merge)

    # Custom model preference should NOT be clobbered
    assert settings["model"] == "claude-3-5-sonnet"
    # Custom permission should NOT be clobbered
    assert settings["permissions"]["defaultMode"] == "dontAcceptEdits"

    # The merge leaves command rules to the policy projection
    assert settings["permissions"]["allow"] == ["Bash(my_custom_script:*)"]


@pytest.mark.ci
def test_opencode_merge_non_destructive():
    existing = {
        "agent": {
            "explore": {"model": "my-custom-model"},
        },
        "custom_key": 123,
    }
    defaults = {
        "agent": {
            "explore": {"model": "default-explore"},
            "general": {"model": "default-general"},
        },
        "new_key": "val",
    }

    merge_dicts_non_destructive(existing, defaults)

    assert existing["agent"]["explore"]["model"] == "my-custom-model"
    assert existing["agent"]["general"]["model"] == "default-general"
    assert existing["custom_key"] == 123
    assert existing["new_key"] == "val"


def test_mcp_servers_added_when_absent():
    """Baseline MCP servers are added to settings that have none."""
    merge = merge_claude_settings({})
    settings = _written(merge)

    for name in BASELINE_MCP_SERVERS:
        assert name in settings["mcpServers"]
        assert any(f"mcpServers.{name}" in c for c in merge.changes)


def test_attribution_added_when_absent():
    """Baseline attribution settings are added to clear PR and commit trailers."""
    merge = merge_claude_settings({})
    settings = _written(merge)

    assert settings["attribution"] == BASELINE_ATTRIBUTION
    assert any("attribution.pr" in c for c in merge.changes)
    assert any("attribution.commit" in c for c in merge.changes)
    assert any("attribution.sessionUrl" in c for c in merge.changes)


def test_existing_attribution_is_never_clobbered():
    """Custom attribution settings survive the merge without being overwritten."""
    existing = {
        "attribution": {
            "pr": "Custom PR footer",
            "commit": "Assisted-by: Developer",
            "sessionUrl": True,
        }
    }
    merge = merge_claude_settings(existing)
    settings = _written(merge)

    assert settings["attribution"]["pr"] == "Custom PR footer"
    assert settings["attribution"]["commit"] == "Assisted-by: Developer"
    assert settings["attribution"]["sessionUrl"] is True
    assert not any("attribution" in c for c in merge.changes)


def test_existing_mcp_server_is_never_clobbered():
    """A hand-configured server keeps its definition, credentials included.

    ADR 0015 exists because overwriting these destroys API keys that cannot be
    regenerated by the setup step.
    """
    name = next(iter(BASELINE_MCP_SERVERS))
    existing = {
        "mcpServers": {
            name: {"command": "custom", "args": ["--mine"], "env": {"API_KEY": "secret"}},
            "obsidian": {"type": "http", "url": "http://127.0.0.1:27123/mcp/"},
        }
    }

    merge = merge_claude_settings(existing)
    settings = _written(merge)

    assert settings["mcpServers"][name]["command"] == "custom"
    assert settings["mcpServers"][name]["env"]["API_KEY"] == "secret"
    assert settings["mcpServers"]["obsidian"]["url"] == "http://127.0.0.1:27123/mcp/"
    assert not any("mcpServers" in c for c in merge.changes)


def test_unrelated_settings_survive_the_merge():
    """Keys the baseline knows nothing about are carried through untouched."""
    merge = merge_claude_settings({"statusLine": {"type": "command"}, "model": "sonnet"})
    settings = _written(merge)

    assert settings["statusLine"] == {"type": "command"}
    assert settings["model"] == "sonnet"  # existing preference wins over the baseline


