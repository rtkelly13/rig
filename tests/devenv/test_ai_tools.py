    home = tmp_path / "devenv-home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("USERPROFILE", str(home))
    monkeypatch.delenv("CLAUDE_SESSION_LEDGER_DIR", raising=False)
