class TestUnlinkProject:
    def test_removes_existing_symlink(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
        projects_dir = tmp_path / "projects"
        projects_dir.mkdir()
        target = tmp_path / "target"
        target.mkdir()
        link = projects_dir / "mylink"
        dir_link(link, target)

        monkeypatch.setattr("desktop_manager.projects.get_projects_dir", lambda: projects_dir)

        removed = unlink_project("mylink")
        assert removed == link
        assert not link.exists()

    def test_raises_file_not_found_for_missing_name(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
        projects_dir = tmp_path / "projects"
        projects_dir.mkdir()

        monkeypatch.setattr("desktop_manager.projects.get_projects_dir", lambda: projects_dir)

        with pytest.raises(FileNotFoundError, match="No linked project named 'ghost'"):
            unlink_project("ghost")

    def test_raises_value_error_for_plain_directory(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
        projects_dir = tmp_path / "projects"
        projects_dir.mkdir()
        plain_dir = projects_dir / "plaindir"
        plain_dir.mkdir()

        monkeypatch.setattr("desktop_manager.projects.get_projects_dir", lambda: projects_dir)

        with pytest.raises(ValueError, match="not a symlink or junction"):
            unlink_project("plaindir")

    @pytest.mark.parametrize("name", ["../outside", "nested/child", "nested\\child", "..", ".", ""])
    def test_refuses_paths_before_touching_the_filesystem(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path, name: str
    ) -> None:
        projects_dir = tmp_path / "projects"
        nested = projects_dir / "nested"
        child = nested / "child"
        child.mkdir(parents=True)
        outside = tmp_path / "outside"
        outside.write_text("keep", encoding="utf-8")

        def fail() -> Path:
            raise AssertionError("unlink_project looked up the projects dir before validating the name")

        monkeypatch.setattr("desktop_manager.projects.get_projects_dir", fail)

        with pytest.raises(ValueError, match="is not a project name"):
            unlink_project(name)
        assert child.is_dir()
        assert outside.read_text(encoding="utf-8") == "keep"
