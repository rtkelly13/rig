class TestExtractRepoSummary:
    def test_prefers_agents_md_over_readme(self, tmp_path: Path) -> None:
        (tmp_path / "AGENTS.md").write_text("# Agents\n\nFrom agents file.\n", encoding="utf-8")
        (tmp_path / "README.md").write_text("# Readme\n\nFrom readme file.\n", encoding="utf-8")
        assert extract_repo_summary(tmp_path) == "From agents file."

    def test_falls_back_to_readme_when_no_agents_md(self, tmp_path: Path) -> None:
        (tmp_path / "README.md").write_text("# Readme\n\nFrom readme file.\n", encoding="utf-8")
        assert extract_repo_summary(tmp_path) == "From readme file."

    def test_returns_empty_when_no_files(self, tmp_path: Path) -> None:
        assert extract_repo_summary(tmp_path) == ""

    def test_skips_agents_md_with_empty_summary_uses_readme(self, tmp_path: Path) -> None:
        (tmp_path / "AGENTS.md").write_text("# Title\n\n## Section\n\nOnly under section.\n", encoding="utf-8")
        (tmp_path / "README.md").write_text("# Readme\n\nGood description.\n", encoding="utf-8")
        assert extract_repo_summary(tmp_path) == "Good description."


