class TestLoadManagedProjectsErrors:
    def test_raises_value_error_when_top_level_not_dict(self, tmp_path: Path) -> None:
        config = tmp_path / "managed-projects.json"
        config.write_text(json.dumps([{"name": "x", "repo": "y"}]), encoding="utf-8")
        with pytest.raises(ValueError, match="Invalid managed-project config"):
            load_managed_projects(config)

    def test_raises_value_error_when_projects_not_list(self, tmp_path: Path) -> None:
        config = tmp_path / "managed-projects.json"
        config.write_text(json.dumps({"projects": "not-a-list"}), encoding="utf-8")
        with pytest.raises(ValueError, match="Invalid managed-project config"):
            load_managed_projects(config)

    def test_raises_value_error_when_project_entry_not_dict(self, tmp_path: Path) -> None:
        config = tmp_path / "managed-projects.json"
        config.write_text(json.dumps({"projects": ["just-a-string"]}), encoding="utf-8")
        with pytest.raises(ValueError, match="Invalid managed-project entry"):
            load_managed_projects(config)

    def test_disabled_project_loaded_but_flagged(self, tmp_path: Path) -> None:
        config = tmp_path / "managed-projects.json"
        config.write_text(
            json.dumps({"projects": [{"name": "alpha", "repo": "https://github.com/o/alpha", "enabled": False}]}),
            encoding="utf-8",
        )
        projects = load_managed_projects(config)
        assert len(projects) == 1
        assert projects[0].enabled is False

    def test_optional_fields_default_correctly(self, tmp_path: Path) -> None:
        config = tmp_path / "managed-projects.json"
        config.write_text(
            json.dumps({"projects": [{"name": "beta", "repo": "https://github.com/o/beta"}]}),
            encoding="utf-8",
        )
        projects = load_managed_projects(config)
        assert len(projects) == 1
        p = projects[0]
        assert p.description == ""
        assert p.branch is None
        assert p.enabled is True
        assert p.clone is True
        assert p.link is True


