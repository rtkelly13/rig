class TestExtractSummaryFromFile:
    def test_returns_first_paragraph_after_h1(self, tmp_path: Path) -> None:
        md = tmp_path / "README.md"
        md.write_text("# My Project\n\nShort description here.\n\n## Details\n\nMore.\n", encoding="utf-8")
        assert _extract_summary_from_file(md) == "Short description here."

    def test_returns_empty_string_when_no_h1(self, tmp_path: Path) -> None:
        md = tmp_path / "README.md"
        md.write_text("Just some text without a heading.\n", encoding="utf-8")
        assert _extract_summary_from_file(md) == ""

    def test_returns_empty_string_when_h1_only(self, tmp_path: Path) -> None:
        md = tmp_path / "README.md"
        md.write_text("# Title\n\n## Section\n\nContent only under section.\n", encoding="utf-8")
        assert _extract_summary_from_file(md) == ""

    def test_skips_autogenerated_frontmatter_returns_overview(self, tmp_path: Path) -> None:
        md = tmp_path / "AGENTS.md"
        md.write_text(
            "# Agents\n\nGenerated: 2026-01-01\n\n## OVERVIEW\n\nActual description.\n",
            encoding="utf-8",
        )
        assert _extract_summary_from_file(md) == "Actual description."

    def test_returns_empty_when_oserror(self, tmp_path: Path) -> None:
        missing = tmp_path / "nonexistent.md"
        assert _extract_summary_from_file(missing) == ""

    def test_multiline_paragraph_joined(self, tmp_path: Path) -> None:
        md = tmp_path / "README.md"
        md.write_text("# Title\n\nLine one.\nLine two.\n\n## More\n", encoding="utf-8")
        assert _extract_summary_from_file(md) == "Line one. Line two."

    def test_overview_section_used_when_no_paragraph(self, tmp_path: Path) -> None:
        md = tmp_path / "README.md"
        md.write_text("# Title\n\n## OVERVIEW\n\nOverview description.\n", encoding="utf-8")
        assert _extract_summary_from_file(md) == "Overview description."


