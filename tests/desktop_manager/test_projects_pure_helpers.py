"""Unit tests for pure helper functions in ``desktop_manager.projects``.

Covers the parts of ``projects.py`` not exercised by ``test_projects.py``:
- ``_strip_markdown_inline`` – inline-markup removal
- ``_extract_summary_from_file`` – paragraph extraction from Markdown files
- ``extract_repo_summary`` – AGENTS.md / README.md priority + OVERVIEW fallback
- ``infer_repo_name`` – additional URL / path edge cases
- ``load_managed_projects`` – validation error paths
- ``unlink_project`` – symlink removal and error branches
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from desktop_manager.projects import (
    _extract_summary_from_file,  # pyright: ignore[reportPrivateUsage]
    _strip_markdown_inline,  # pyright: ignore[reportPrivateUsage]
    extract_repo_summary,
    infer_repo_name,
    load_managed_projects,
    unlink_project,
)
from tests.links import dir_link

# ---------------------------------------------------------------------------
# _strip_markdown_inline
# ---------------------------------------------------------------------------


class TestStripMarkdownInline:
    def test_removes_markdown_link(self) -> None:
        assert _strip_markdown_inline("[Click here](https://example.com)") == "Click here"

    def test_removes_bold(self) -> None:
        assert _strip_markdown_inline("**bold text**") == "bold text"

    def test_removes_italic(self) -> None:
        assert _strip_markdown_inline("*italic text*") == "italic text"

    def test_removes_inline_code(self) -> None:
        assert _strip_markdown_inline("`code snippet`") == "code snippet"

    def test_removes_underscore_emphasis(self) -> None:
        assert _strip_markdown_inline("_underscored_") == "underscored"

    def test_removes_double_underscore_bold(self) -> None:
        assert _strip_markdown_inline("__double underscore__") == "double underscore"

    def test_strips_surrounding_whitespace(self) -> None:
        assert _strip_markdown_inline("  plain text  ") == "plain text"

    def test_plain_text_unchanged(self) -> None:
        assert _strip_markdown_inline("No markup here") == "No markup here"

    def test_mixed_markup(self) -> None:
        result = _strip_markdown_inline("Use **`uv`** for [dependency management](https://astral.sh).")
        assert result == "Use uv for dependency management."


