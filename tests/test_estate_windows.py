"""Tests for the Windows side of `estate`: sizing, registry apps, and the volume scan."""

from __future__ import annotations

import os
import pathlib

import pytest

from rig.estate import apps_windows, disksize, volume
from rig.estate.apps_windows import UninstallEntry
from rig.estate.volume import Folder, Hog

GB = 1024**3


def _f(path: str, gb: float) -> Folder:
    return Folder(path=path, allocated=int(gb * GB), size=int(gb * GB), files=1)


@pytest.mark.ci
def test_measure_counts_hardlink_only_when_every_link_is_inside(tmp_path: pathlib.Path) -> None:
    tree = tmp_path / "venv"
    tree.mkdir()
    (tree / "own.bin").write_bytes(b"x" * 10_000)
    cache = tmp_path / "cache"
    cache.mkdir()
    shared = cache / "shared.bin"
    shared.write_bytes(b"y" * 50_000)
    os.link(shared, tree / "shared.bin")
    inside = tree / "twin-a.bin"
    inside.write_bytes(b"z" * 20_000)
    os.link(inside, tree / "twin-b.bin")

    size = disksize.measure_windows(tree)

    # own.bin, plus the twin pair once; shared.bin stays on disk via the cache.
    assert size.freeable == disksize._allocated(10_000) + disksize._allocated(20_000)
    assert size.shared == disksize._allocated(50_000)


@pytest.mark.ci
def test_load_skips_wiztree_banner_and_keeps_commas(tmp_path: pathlib.Path) -> None:
    csv = tmp_path / "export.csv"
    csv.write_text(
        "\ufeffGenerated by WizTree 4.32 (You can hide this message by making a donation)\n"
        "File Name,Size,Allocated,Modified,Attributes,Files,Folders,DRIVECAPACITY,FREESPACE,USEDSPACE,RESERVEDSPACE\n"
        '"C:\\",900,1000,2026/10/08 10:00:00,0,10,3,2000,100,1900,0\n'
        '"C:\\Users\\a, b\\",400,500,2026/10/08 10:00:00,0,4,1\n'
        '"C:\\tiny\\",1,1,2026/10/08 10:00:00,0,1,0\n',
        encoding="utf-8",
    )

    folders = volume.load(csv, floor=10)

    assert [(f.path, f.allocated) for f in folders] == [("C:", 1000), ("C:\\Users\\a, b", 500)]


@pytest.mark.ci
def test_partition_counts_each_subtree_once_at_outermost_match() -> None:
    folders = [
        _f("C:\\code", 100),
        _f("C:\\code\\repo\\temp", 40),
        _f("C:\\code\\repo\\temp\\wt\\packages", 30),
        _f("C:\\code\\repo\\temp\\wt\\packages\\x\\bin", 10),
        _f("C:\\code\\repo\\node_modules", 5),
        _f("C:\\code\\repo\\.venv", 3),
        _f("C:\\Program Files\\App\\bin", 50),
    ]

    parts = volume.partition(folders, pathlib.Path("C:\\code"))

    assert parts["scratch in temp/"] == 40 * GB
    assert "NuGet packages" not in parts
    assert parts["node_modules"] == 5 * GB
    assert parts["python venv"] == 3 * GB
    # Program Files' bin is outside the code root, so it is not build output.
    assert "build output" not in parts
    assert parts["source + everything else (code root)"] == 52 * GB


@pytest.mark.ci
def test_partition_is_not_split_by_a_sibling_that_sorts_inside_the_subtree() -> None:
    folders = [
        _f("C:\\code", 100),
        _f("C:\\code\\repo\\temp", 40),
        _f("C:\\code\\repo\\temp-old", 1),
        _f("C:\\code\\repo\\temp\\wt\\node_modules", 10),
    ]

    parts = volume.partition(folders, pathlib.Path("C:\\code"))

    assert parts["scratch in temp/"] == 40 * GB
    assert "node_modules" not in parts


@pytest.mark.ci
def test_tree_drills_largest_first_and_respects_floor_and_depth() -> None:
    folders = [
        _f("C:", 900),
        _f("C:\\Users", 500),
        _f("C:\\Windows", 100),
        _f("C:\\Users\\me", 490),
        _f("C:\\Users\\me\\AppData", 300),
        _f("C:\\Users\\small", 1),
    ]

    drill = volume.tree(folders, min_bytes=50 * GB, max_depth=2)

    assert [(row.level, row.folder.path) for row in drill] == [
        (0, "C:"),
        (1, "C:\\Users"),
        (2, "C:\\Users\\me"),
        (1, "C:\\Windows"),
    ]


@pytest.mark.ci
def test_hogs_expand_env_and_match_one_segment_wildcards(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("LOCALAPPDATA", "C:\\Users\\me\\AppData\\Local")
    catalogue = (
        Hog("WSL", r"%LOCALAPPDATA%\Packages\*Canonical*", "compact", "review"),
        Hog("uv", r"%LOCALAPPDATA%\uv\cache", "prune", "safe"),
        Hog("absent", r"%LOCALAPPDATA%\nothing", "-", "safe"),
    )
    folders = [
        _f("C:\\Users\\me\\AppData\\Local\\Packages\\CanonicalGroupLimited.Ubuntu", 20),
        _f("C:\\Users\\me\\AppData\\Local\\Packages\\CanonicalGroupLimited.Ubuntu\\LocalState", 20),
        _f("C:\\Users\\me\\AppData\\Local\\uv\\cache", 7),
    ]

    found = volume.hogs(folders, catalogue)

    assert [(hit.hog.label, hit.allocated) for hit in found] == [("WSL", 20 * GB), ("uv", 7 * GB)]


@pytest.mark.ci
def test_root_files_is_root_minus_top_level_folders() -> None:
    folders = [_f("C:", 900), _f("C:\\Users", 500), _f("C:\\Windows", 380), _f("C:\\Users\\me", 400)]

    assert volume.root_files(folders) == 20 * GB


@pytest.mark.ci
def test_entry_to_app_uses_estimated_size_and_install_date() -> None:
    app = apps_windows.entry_to_app(
        UninstallEntry(
            display_name="Docker Desktop", display_version="4.40", estimated_size=2048, install_date="20240101"
        ),
        measure=False,
    )

    assert app is not None
    assert app.bytes_used == 2048 * 1024
    assert app.version == "4.40"
    assert app.modified.year == 2024
    assert app.is_dormant


