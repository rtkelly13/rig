using Rig.Core.Estate;
using Rig.Core.Processes;
using Rig.Core.Tests.Fakes;
using Rig.Core.Tests.Otel;

namespace Rig.Core.Tests.Estate;

/// <summary>
/// <see cref="Volume"/> over folders built in memory and a WizTree export written to a temp folder, and
/// <see cref="WizTreeExport"/> with WizTree and <c>tasklist</c> faked. Ported from <c>tests/test_estate_windows.py</c>.
/// </summary>
public sealed class VolumeTests : IDisposable
{
    private const long GB = 1024L * 1024 * 1024;

    private readonly TempDir _root = new();

    public void Dispose() => _root.Dispose();

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    private static Folder F(string path, long gb) => new(path, gb * GB, gb * GB, 1);

    [Fact]
    public void An_export_loads_past_wiztrees_banner_keeping_commas_and_dropping_folders_under_the_floor()
    {
        var csv = Path.Join(_root.Path, "export.csv");
        File.WriteAllText(
            csv,
            "\ufeffGenerated by WizTree 4.32 (You can hide this message by making a donation)\n"
            + "File Name,Size,Allocated,Modified,Attributes,Files,Folders,DRIVECAPACITY,FREESPACE,USEDSPACE,RESERVEDSPACE\n"
            + "\"C:\\\",900,1000,2026/10/08 10:00:00,0,10,3,2000,100,1900,0\n"
            + "\"C:\\Users\\a, b\\\",400,500,2026/10/08 10:00:00,0,4,1\n"
            + "\"C:\\say \"\"hi\"\"\\\",400,500,2026/10/08 10:00:00,0,4,1\n"
            + "\"C:\\tiny\\\",1,1,2026/10/08 10:00:00,0,1,0\n"
            + "\"C:\\blank\\\",1,,2026/10/08 10:00:00,0,1,0\n");

        var folders = Volume.Load(csv, floor: 10);

        Assert.Equal(
            [("C:", 1000L, 900L, 10L), ("C:\\Users\\a, b", 500L, 400L, 4L), ("C:\\say \"hi\"", 500L, 400L, 4L)],
            folders.Select(f => (f.Path, f.Allocated, f.Size, f.Files)));
    }

    [Fact]
    public void An_export_with_a_cell_that_is_not_a_number_is_refused()
    {
        var csv = Path.Join(_root.Path, "export.csv");
        File.WriteAllText(csv, "banner\nheader\n\"C:\\\",900,lots,x,0,10\n");

        _ = Assert.Throws<InvalidDataException>(() => Volume.Load(csv));
    }

    [Fact]
    public void The_partition_counts_each_subtree_once_at_its_outermost_match()
    {
        Folder[] folders =
        [
            F("C:\\code", 100),
            F("C:\\code\\repo\\temp", 40),
            F("C:\\code\\repo\\temp\\wt\\packages", 30),
            F("C:\\code\\repo\\temp\\wt\\packages\\x\\bin", 10),
            F("C:\\code\\repo\\node_modules", 5),
            F("C:\\code\\repo\\.venv", 3),
            F("C:\\Program Files\\App\\bin", 50),
        ];

        var parts = Volume.Partition(folders, "C:\\code");

        // Program Files' bin is outside the code root, so it is not build output.
        Assert.Equal(
            [
                ("source + everything else (code root)", 52 * GB),
                ("scratch in temp/", 40 * GB),
                ("node_modules", 5 * GB),
                ("python venv", 3 * GB),
            ],
            parts.Select(part => (part.Key, part.Value)));
    }

    [Fact]
    public void The_partition_is_not_split_by_a_sibling_that_sorts_inside_the_subtree()
    {
        Folder[] folders = [F("C:\\code", 100), F("C:\\code\\repo\\temp", 40), F("C:\\code\\repo\\temp-old", 1), F("C:\\code\\repo\\temp\\wt\\node_modules", 10)];

        var parts = Volume.Partition(folders, "C:\\code").ToDictionary();

        Assert.Equal(40 * GB, parts["scratch in temp/"]);
        Assert.False(parts.ContainsKey("node_modules"));
    }

    [Fact]
    public void The_drill_down_goes_largest_first_within_the_floor_and_depth()
    {
        Folder[] folders = [F("C:", 900), F("C:\\Users", 500), F("C:\\Windows", 100), F("C:\\Users\\me", 490), F("C:\\Users\\me\\AppData", 300), F("C:\\Users\\small", 1)];

        var drill = Volume.Tree(folders, 50 * GB, maxDepth: 2);

        Assert.Equal([(0, "C:"), (1, "C:\\Users"), (2, "C:\\Users\\me"), (1, "C:\\Windows")], drill.Select(row => (row.Level, row.Folder.Path)));
    }

    [Fact]
    public void A_hog_expands_the_environment_and_matches_one_segment_wildcards()
    {
        Hog[] catalogue =
        [
            new("WSL", @"%LOCALAPPDATA%\Packages\*Canonical*", "compact", "review"),
            new("uv", @"%LOCALAPPDATA%\uv\cache", "prune", "safe"),
            new("absent", @"%LOCALAPPDATA%\nothing", "-", "safe"),
            new("unset", @"%NOT_SET%\uv\cache", "-", "safe"),
        ];
        Folder[] folders =
        [
            F("C:\\Users\\me\\AppData\\Local\\Packages\\CanonicalGroupLimited.Ubuntu", 20),
            F("C:\\Users\\me\\AppData\\Local\\Packages\\CanonicalGroupLimited.Ubuntu\\LocalState", 20),
            F("C:\\Users\\me\\AppData\\Local\\uv\\cache", 7),
        ];

        var found = Volume.Hogs(folders, catalogue, name => name == "LOCALAPPDATA" ? "C:\\Users\\me\\AppData\\Local" : null);

        Assert.Equal([("WSL", 20 * GB), ("uv", 7 * GB)], found.Select(hit => (hit.Hog.Label, hit.Allocated)));
    }

    [Fact]
    public void The_files_at_the_root_are_the_root_less_its_top_level_folders()
    {
        Folder[] folders = [F("C:", 900), F("C:\\Users", 500), F("C:\\Windows", 380), F("C:\\Users\\me", 400)];

        Assert.Equal(20 * GB, Volume.RootFiles(folders));
    }

    [Fact]
    public async Task An_export_is_done_when_the_file_is_written_and_wiztree_has_exited()
    {
        var wizTree = _root.File("WizTree64.exe");
        var output = _root.File("wiztree-c.csv");
        var clock = new ManualClock(DateTimeOffset.UnixEpoch);
        var running = new Ran(0, "WizTree64.exe   1234 Console   1   400,000 K\n", string.Empty);
        var proc = new FakeProc().Answer(running, "tasklist");
        var polls = 0;
        var export = new WizTreeExport(proc, clock, async (delay, token) =>
        {
            await clock.SleepAsync(delay, token);
            if (++polls == 2)
            {
                await File.WriteAllTextAsync(output, "data", token);
            }
            else if (polls == 3)
            {
                _ = proc.Answer(new Ran(0, "INFO: No tasks are running which match the specified criteria.\n", string.Empty), "tasklist");
            }
        }, wizTree);

        await export.RunAsync("c:", output, cancellationToken: Token);

        Assert.Equal([wizTree, "c:\\", $"/export={output}", "/admin=1", "/exportfolders=1", "/exportfiles=0"], proc.Requests[0].Argv);
        Assert.Equal(3, polls);
        Assert.All(clock.Slept, slept => Assert.Equal(TimeSpan.FromSeconds(3), slept));
    }

    [Fact]
    public async Task An_export_that_never_finishes_times_out()
    {
        var clock = new ManualClock(DateTimeOffset.UnixEpoch);
        var export = new WizTreeExport(new FakeProc(), clock, clock.SleepAsync, _root.File("WizTree64.exe"));

        var failure = await Assert.ThrowsAsync<TimeoutException>(() => export.RunAsync("C", Path.Join(_root.Path, "out.csv"), TimeSpan.FromSeconds(10), Token));

        Assert.Contains("within 10s", failure.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task An_export_without_wiztree_says_how_to_install_it()
    {
        var clock = new ManualClock(DateTimeOffset.UnixEpoch);
        var export = new WizTreeExport(new FakeProc(), clock, clock.SleepAsync, Path.Join(_root.Path, "absent.exe"));

        var failure = await Assert.ThrowsAsync<FileNotFoundException>(() => export.RunAsync("C", Path.Join(_root.Path, "out.csv"), cancellationToken: Token));

        Assert.Contains("winget install", failure.Message, StringComparison.Ordinal);
    }
}
